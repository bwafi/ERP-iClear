    public static function resolve(string $method, string $path): ?string
    {
        $method = strtoupper($method);
        $path = strtolower(trim(parse_url($path, PHP_URL_PATH) ?: '', '/'));
        $path = preg_replace('#^(?:index\.php/)+#', '', $path) ?? $path;

        foreach (self::ROUTES[$method] ?? [] as $pattern => $permission) {
            $regex = preg_quote(strtolower($pattern), '#');
            $regex = str_replace(['\\(\\:num\\)', '\\(\\:any\\)', '\\(\\:segment\\)'], ['[0-9]+', '.+', '[^/]+'], $regex);
            if (preg_match('#^' . $regex . '$#', $path) === 1) {
                return $permission;
            }
        }

        return null;
    }

    public static function isGranted(string $permission, array $roleIds, array $menuRows): bool
    {
        $roleIds = array_fill_keys(array_map('strval', $roleIds), true);
        foreach ($menuRows as $menu) {
            $id = (string) (is_array($menu) ? ($menu['idmenu'] ?? '') : ($menu->idmenu ?? ''));
            $routeRole = strtolower(trim((string) (is_array($menu) ? ($menu['roles'] ?? '') : ($menu->roles ?? ''))));
            if ($id !== '' && isset($roleIds[$id]) && $routeRole === strtolower($permission)) {
                return true;
            }
        }

        return false;
    }
